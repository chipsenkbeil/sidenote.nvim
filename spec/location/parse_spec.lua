local location = require("sidenote.location")

describe("location.parse file scope", function()
    it("parses a bare path", function()
        local loc = location.parse("lua/lobby.lua")
        assert.eq(loc.path, "lua/lobby.lua")
        assert.eq(loc.scope, "file")
        assert.eq(loc.line_start, 0)
        assert.eq(loc.line_end, 0)
    end)

    it("parses an absolute path", function()
        assert.eq(location.parse("/abs/lua/lobby.lua").path, "/abs/lua/lobby.lua")
    end)

    it("parses a path with no directory", function()
        assert.eq(location.parse("init.lua").path, "init.lua")
    end)
end)

describe("location.parse line scope", function()
    it("parses a single line", function()
        local loc = location.parse("lua/lobby.lua:15")
        assert.eq(loc.path, "lua/lobby.lua")
        assert.eq(loc.scope, "lines")
        assert.eq(loc.line_start, 15)
        assert.eq(loc.line_end, 15)
        assert.eq(loc.col_start, 0)
    end)

    it("parses a whole-line range", function()
        local loc = location.parse("lua/lobby.lua:15-20")
        assert.eq(loc.scope, "lines")
        assert.eq(loc.line_start, 15)
        assert.eq(loc.line_end, 20)
        assert.eq(loc.col_start, 0)
        assert.eq(loc.col_end, 0)
    end)

    it("accepts a one-line range written as a range", function()
        local loc = location.parse("lua/lobby.lua:15-15")
        assert.eq(loc.line_start, 15)
        assert.eq(loc.line_end, 15)
    end)
end)

describe("location.parse range scope", function()
    it("parses a column-precise range", function()
        local loc = location.parse("lua/lobby.lua:15:4-20:10")
        assert.eq(loc.scope, "range")
        assert.eq(loc.line_start, 15)
        assert.eq(loc.col_start, 4)
        assert.eq(loc.line_end, 20)
        assert.eq(loc.col_end, 10)
    end)

    it("parses a range within one line", function()
        local loc = location.parse("lua/lobby.lua:15:4-15:10")
        assert.eq(loc.scope, "range")
        assert.eq(loc.line_start, 15)
        assert.eq(loc.line_end, 15)
    end)
end)

describe("location.parse rejections", function()
    it("rejects a mixed form with a column only on the left", function()
        local loc, err = location.parse("lua/lobby.lua:15:4-20")
        assert.is_nil(loc)
        assert.match(err, "mixed")
    end)

    it("rejects a mixed form with a column only on the right", function()
        local loc, err = location.parse("lua/lobby.lua:15-20:10")
        assert.is_nil(loc)
        assert.match(err, "mixed")
    end)

    it("rejects an inverted line range", function()
        local loc, err = location.parse("lua/lobby.lua:20-15")
        assert.is_nil(loc)
        assert.match(err, "before")
    end)

    it("rejects an inverted column range on one line", function()
        local loc, err = location.parse("lua/lobby.lua:15:10-15:4")
        assert.is_nil(loc)
        assert.match(err, "before")
    end)

    it("rejects line zero", function()
        local loc, err = location.parse("lua/lobby.lua:0")
        assert.is_nil(loc)
        assert.match(err, "1%-indexed")
    end)

    it("rejects column zero, which is not the same as omitting a column", function()
        local loc, err = location.parse("lua/lobby.lua:15:0-20:1")
        assert.is_nil(loc)
        assert.match(err, "1%-indexed")
    end)

    it("rejects an empty string", function()
        local loc, err = location.parse("")
        assert.is_nil(loc)
        assert.is_type(err, "string")
    end)

    it("rejects a position with no path", function()
        local loc, err = location.parse(":15")
        assert.is_nil(loc)
        assert.is_type(err, "string")
    end)

    it("rejects a non-string, saying so rather than calling it empty", function()
        local loc, err = location.parse(nil)
        assert.is_nil(loc)
        assert.contains(err, "string")
    end)
end)

describe("location.parse paths containing colons", function()
    it("splits greedily so a colon in the path survives", function()
        local loc = location.parse("weird:dir/file.lua:15")
        assert.eq(loc.path, "weird:dir/file.lua")
        assert.eq(loc.line_start, 15)
    end)

    it("treats a path ending in a colon-word as file scope", function()
        local loc = location.parse("weird:dir/file.lua")
        assert.eq(loc.path, "weird:dir/file.lua")
        assert.eq(loc.scope, "file")
    end)
end)
